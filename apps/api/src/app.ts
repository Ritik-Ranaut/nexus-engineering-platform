import cors from "cors";
import express from "express";
import cookieParser from "cookie-parser";
import helmet from "helmet";
import { env } from "./config/env.js";
import { errorHandler, notFoundHandler } from "./middleware/error.middleware.js";
import authRoutes from "./routes/auth.routes.js";
import projectRoutes from "./routes/project.routes.js";
import aiRoutes from "./routes/ai.routes.js";
import { cancelMission, decideMissionAction, getMission } from "./controllers/mission.controller.js";
import { requireAuth } from "./middleware/auth.middleware.js";

export const createApp = () => {
  const app = express();
  app.disable("x-powered-by");
  app.use(helmet());
  app.use(cors({ origin: env.WEB_ORIGIN, credentials: true }));
  app.use(express.json({ limit: "5mb" }));
  app.use(cookieParser());
  app.get("/api/health", (_request, response) => response.status(200).json({ status: "ok" }));
  app.use("/api/auth", authRoutes);
  app.use("/api/projects", projectRoutes);
  app.use("/api/missions", requireAuth);
  app.get("/api/missions/:missionId", getMission);
  app.post("/api/missions/:missionId/cancel", cancelMission);
  app.post("/api/missions/:missionId/actions/:actionId/decision", decideMissionAction);
  app.use("/api/ai", aiRoutes);
  app.use(notFoundHandler);
  app.use(errorHandler);
  return app;
};
